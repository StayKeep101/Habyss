/**
 * The desktop's look comes from the phone's: this reads the phone app's
 * theme/ (colours, surfaces, radius, spacing, type, motion) and writes
 * apps/desktop/src/theme/phone.generated.ts. Nothing is copied by hand, so a
 * change to the phone's look reaches the desktop the next time this runs.
 *
 *   bun scripts/sync-theme.ts            (phone repo next to this one)
 *   HABYSS_PHONE=/path/to/Habyss bun scripts/sync-theme.ts
 *
 * The phone's theme files import React Native for StyleSheet and screen
 * scaling; those are stubbed here at the design phone's size, so every value
 * comes out exactly as written in the phone's source.
 */
import { plugin } from 'bun';
import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const phone = resolve(process.env.HABYSS_PHONE ?? join(import.meta.dir, '../../Habyss'));

plugin({
    name: 'react-native stubs',
    setup(build) {
        build.module('react-native', () => ({
            loader: 'object',
            exports: {
                StyleSheet: { create: (x: unknown) => x, hairlineWidth: 1 },
                Dimensions: { get: () => ({ width: 390, height: 844 }) },
                PixelRatio: { roundToNearestPixel: (x: number) => x },
                Platform: { OS: 'ios', select: (o: Record<string, unknown>) => o.ios ?? o.default },
            },
        }));
        const easing: any = new Proxy(() => easing, { get: () => easing, apply: () => easing });
        build.module('react-native-reanimated', () => ({ loader: 'object', exports: { Easing: easing, ReduceMotion: { System: 'system' } } }));
    },
});

const { Colors } = await import(join(phone, 'theme/colors.ts'));
const ds = await import(join(phone, 'theme/designSystem.ts'));
const motion = await import(join(phone, 'theme/motion.ts'));

const themes = ['light', 'abyss', 'trueDark'] as const;
const palette = Object.fromEntries(themes.map(t => [t, {
    background: Colors[t].background, textPrimary: Colors[t].textPrimary, textSecondary: Colors[t].textSecondary, textTertiary: Colors[t].textTertiary,
    primary: Colors[t].primary, success: Colors[t].success, warning: Colors[t].warning, error: Colors[t].error, border: Colors[t].border,
}]));
const surfaces = Object.fromEntries(themes.map(t => [t, ds.Surfaces[t]]));
const typography = Object.fromEntries(Object.entries(ds.Typography as Record<string, any>).map(([k, v]) => [k, {
    weight: /700|Bold/.test(v.fontFamily) ? 700 : /500|Medium/.test(v.fontFamily) ? 500 : 400,
    size: v.fontSize, lineHeight: v.lineHeight, ...(v.letterSpacing !== undefined ? { letterSpacing: v.letterSpacing } : {}),
}]));
const elevation = Object.fromEntries(Object.entries(ds.Elevation as Record<string, any>).map(([k, v]) => [k, {
    height: v.shadowOffset?.height ?? 0, opacity: v.shadowOpacity ?? 0, radius: v.shadowRadius ?? 0,
}]));

const out = {
    palettes: palette,
    Surfaces: surfaces,
    Radius: ds.Radius,
    Spacing: ds.Spacing,
    Control: ds.Control,
    Typography: typography,
    Elevation: elevation,
    DURATION: motion.DURATION,
};
const file = join(import.meta.dir, '../apps/desktop/src/theme/phone.generated.ts');
writeFileSync(file, `// Generated by scripts/sync-theme.ts from the phone app's theme/. Do not edit: run \`bun scripts/sync-theme.ts\`.\n${
    Object.entries(out).map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)} as const;`).join('\n\n')}\n`);
console.log(`Wrote ${file}`);
