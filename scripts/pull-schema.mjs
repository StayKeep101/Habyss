#!/usr/bin/env node
/**
 * Writes packages/schema/src/tables.json: the columns the server really has on the tables both apps sync (habits,
 * habit_completions, tasks), read from the live database. Both apps' contract tests check their sync mapping against
 * it, so a column added on the server, or on one app, can't silently go missing on the other.
 *
 *   node scripts/pull-schema.mjs        (after applying a migration that changes these tables)
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const TABLES = ['habits', 'habit_completions', 'tasks'];
const sql = `select table_name, column_name, udt_name from information_schema.columns where table_schema = 'public' and table_name in (${TABLES.map(t => `'${t}'`).join(', ')}) order by table_name, column_name`;
const rows = JSON.parse(execFileSync('node', [new URL('./sql.mjs', import.meta.url).pathname, sql], { encoding: 'utf8' }));
const tables = Object.fromEntries(TABLES.map(t => [t, Object.fromEntries(rows.filter(r => r.table_name === t).map(r => [r.column_name, r.udt_name]))]));
const file = new URL('../packages/schema/src/tables.json', import.meta.url);
writeFileSync(file, `${JSON.stringify({ note: 'Generated by scripts/pull-schema.mjs from the live database. Do not edit.', tables }, null, 2)}\n`);
console.log(`Wrote ${file.pathname}: ${TABLES.map(t => `${t} ${Object.keys(tables[t]).length}`).join(', ')}`);
